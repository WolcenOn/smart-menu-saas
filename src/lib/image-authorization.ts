import 'server-only';
import { getCurrentUserId } from '@/lib/current-user';
import { prisma } from '@/lib/db';

export async function getEditableDish(dishId: string) {
  const userId = await getCurrentUserId();
  if (!userId) return null;
  const dish = await prisma.dish.findFirst({
    where: {
      id: dishId,
      category: { menu: { restaurant: { members: {
        some: { userId, role: { in: ['OWNER', 'EDITOR'] } },
      } } } },
    },
    select: {
      id: true,
      category: { select: { menu: { select: {
        restaurantId: true,
        restaurant: { select: { slug: true } },
      } } } },
    },
  });
  return dish ? {
    dishId: dish.id,
    restaurantId: dish.category.menu.restaurantId,
    slug: dish.category.menu.restaurant.slug,
    userId,
  } : null;
}

export function requestIsSameOrigin(req: Request): boolean {
  const contentType = req.headers.get('content-type')?.split(';')[0]?.trim();
  if (contentType !== 'application/json') return false;

  // Fetch Metadata is generated by browsers and cannot be set from page JavaScript.
  // It also works when a trusted reverse proxy rewrites Request.url internally.
  const site = req.headers.get('sec-fetch-site');
  if (site && site !== 'same-origin') return false;
  const origin = req.headers.get('origin');
  if (site === 'same-origin') return true;
  // Fallback for browsers/clients without Fetch Metadata: exact Origin match.
  return !!origin && origin === new URL(req.url).origin;
}
